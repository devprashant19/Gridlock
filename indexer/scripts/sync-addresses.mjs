#!/usr/bin/env node
// Reads ../deployments/testnet.json and rewrites config.yaml addresses/start_block
// and src/markets.ts (Kuru market -> series symbol). Run after Stream A deploys:
//   pnpm sync && pnpm codegen
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const dep = JSON.parse(readFileSync(resolve(root, "../deployments/testnet.json"), "utf8"));

const markets = Object.entries(dep.series)
  .filter(([, s]) => s.kuruMarket)
  .map(([symbol, s]) => ({ symbol, seriesId: s.seriesId, market: s.kuruMarket.toLowerCase() }));

let cfg = readFileSync(resolve(root, "config.yaml"), "utf8");
const setAddr = (name, addr) => {
  const re = new RegExp(`(- name: ${name}\\n(?:\\s+.*\\n)*?\\s+address:)[^\\n]*`);
  if (!re.test(cfg)) throw new Error(`config.yaml: no address line for ${name}`);
  cfg = cfg.replace(re, `$1 "${addr}"`);
};
setAddr("DeliveryEscrow", dep.contracts.DeliveryEscrow);
setAddr("SeriesFactory", dep.contracts.SeriesFactory);
setAddr("IndexOracle", dep.contracts.IndexOracle);
cfg = cfg.replace(
  /(- name: KuruOrderBook\n(?:\s+.*\n)*?\s+address:)[^\n]*(\n(?:\s+- "0x[0-9a-fA-F]+"\n)*)/,
  `$1\n${markets.map((m) => `          - "${m.market}"`).join("\n")}\n`,
);
cfg = cfg.replace(/start_block: \d+/, `start_block: ${dep.deployBlock ?? 0}`);
writeFileSync(resolve(root, "config.yaml"), cfg);

const ts = `// AUTO-GENERATED by scripts/sync-addresses.mjs from deployments/testnet.json. Do not edit.
export const MARKET_TO_SERIES: Record<string, { symbol: string; seriesId: number }> = {
${markets.map((m) => `  "${m.market}": { symbol: ${JSON.stringify(m.symbol)}, seriesId: ${m.seriesId} },`).join("\n")}
};
`;
writeFileSync(resolve(root, "src/markets.ts"), ts);
console.log(`synced ${markets.length} markets, start_block=${dep.deployBlock}`);
